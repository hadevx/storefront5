const poolFor = (genre) =>
  IDEA_GENRES.includes(genre) ? LOVE_POOL.ideas : FEELING_GENRES.includes(genre) ? LOVE_POOL.feeling : LOVE_POOL.default;

const FORMATS = ["Hardcover", "Paperback", "Collector's Edition"];

const buildBook = (raw, index) => {
  const slug = slugify(raw.title);
  const seed = `${slug}-${raw.author}`;
  const h = hash(seed);
  const badges = raw.badges || [];
  const formats = [
    { name: "Hardcover", price: raw.price, available: true },
    { name: "Paperback", price: Math.round((raw.price - 5.1) * 100) / 100, available: h % 5 !== 0 },
    { name: "Collector's Edition", price: Math.round((raw.price + 14) * 100) / 100, available: h % 3 === 0 },
  ].filter((f) => f.price > 4);

  return {
    id: index + 1,
    slug,
    title: raw.title,
    subtitle: raw.subtitle || null,
    author: raw.author,
    authorSlug: slugify(raw.author),
    genre: raw.genre,
    genreSlug: slugify(raw.genre),
    price: raw.price,
    rating: raw.rating,
    reviews: raw.reviews,
    pages: raw.pages,
    publisher: raw.publisher,
    published: raw.published,
    year: Number(raw.published.slice(0, 4)),
    isbn: isbnFor(slug),
    language: raw.language || "English",
    format: raw.format || FORMATS[0],
    formats,
    stock: raw.stock ?? (h % 11 === 0 ? 2 : 4 + (h % 24)),
    cover: { palette: raw.palette, template: raw.template },
    hook: raw.hook,
    description: raw.description,
    featured: badges.includes("featured"),
    bestseller: badges.includes("bestseller"),
    newRelease: badges.includes("new"),
    staffPick: badges.includes("staff-pick"),
    rank: raw.rank ?? null,
    collections: raw.collections || [],
    whyLove: pickMany(poolFor(raw.genre), seed, 3),
    praise: pickMany(PRAISE_POOL, seed + "praise", 3),
  };
};

export const BOOKS = RAW.map(buildBook);

