export const bookBySlug = (slug) => BOOKS.find((b) => b.slug === slug);
export const booksByAuthor = (authorSlug) => BOOKS.filter((b) => b.authorSlug === authorSlug);
export const booksByGenre = (genreSlug) => BOOKS.filter((b) => b.genreSlug === genreSlug);
export const booksByCollection = (collectionSlug) => BOOKS.filter((b) => b.collections.includes(collectionSlug));

export const FEATURED_BOOK = BOOKS.find((b) => b.featured) || BOOKS[0];

export const BESTSELLERS = BOOKS.filter((b) => b.rank).sort((a, b) => a.rank - b.rank);

export const NEW_RELEASES = BOOKS.filter((b) => b.newRelease).sort(
  (a, b) => new Date(b.published) - new Date(a.published),
);

export const STAFF_PICKS = BOOKS.filter((b) => b.staffPick);

export const relatedBooks = (book, count = 4) =>
  BOOKS.filter((b) => b.slug !== book.slug)
    .map((b) => ({
      b,
      score:
        (b.genre === book.genre ? 3 : 0) +
        (b.author === book.author ? 4 : 0) +
        b.collections.filter((c) => book.collections.includes(c)).length * 2 +
        (Math.abs(b.price - book.price) < 3 ? 1 : 0),
    }))
    .sort((x, y) => y.score - x.score || y.b.rating - x.b.rating)
    .slice(0, count)
    .map((x) => x.b);

export const searchBooks = (query) => {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return BOOKS.map((b) => {
    const title = b.title.toLowerCase();
    let score = 0;
    if (title.startsWith(q)) score += 10;
    else if (title.includes(q)) score += 6;
    if (b.author.toLowerCase().includes(q)) score += 5;
    if (b.genre.toLowerCase().includes(q)) score += 3;
    if (b.publisher.toLowerCase().includes(q)) score += 1;
    if ((b.hook || "").toLowerCase().includes(q)) score += 1;
    return { b, score };
  })
    .filter((x) => x.score > 0)
    .sort((x, y) => y.score - x.score || y.b.rating - x.b.rating)
    .map((x) => x.b);
};

